// Arabic plural forms: 1 → singular (no digit), 2 → dual, 3–10 → plural,
// 11–99 → singular accusative, 100+/0 follow the last two digits.
function plural(
  n: number,
  forms: { one: string; two: string; few: string; many: string; other: string },
): string {
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  const m = n % 100;
  if (n === 0 || (m >= 3 && m <= 10)) return `${n} ${forms.few}`;
  if (m >= 11 && m <= 99) return `${n} ${forms.many}`;
  return `${n} ${forms.other}`;
}

